import os

import requests
from dotenv import load_dotenv

from app.prompts.forecast_prompts import (
    SYSTEM_PROMPT,
    build_forecast_prompt,
)


# --------------------------------------------------
# LOAD ENVIRONMENT VARIABLES
# --------------------------------------------------

load_dotenv()


OLLAMA_BASE_URL = os.getenv(
    "OLLAMA_BASE_URL",
    "http://localhost:11434",
).rstrip("/")


OLLAMA_MODEL = os.getenv(
    "OLLAMA_MODEL",
    "qwen3:1.7b",
)


# --------------------------------------------------
# CHECK OLLAMA CONNECTION
# --------------------------------------------------

def check_ollama_connection() -> bool:
    """
    Check whether the local Ollama service
    is available.
    """

    try:

        response = requests.get(
            f"{OLLAMA_BASE_URL}/api/tags",
            timeout=5,
        )

        return response.status_code == 200

    except requests.RequestException:

        return False


# --------------------------------------------------
# GENERATE FORECAST EXPLANATION
# --------------------------------------------------

def generate_forecast_explanation(
    trend_summary: dict,
    forecast_result: dict,
    capacity: float | None = None,
    model_name: str | None = None,
    prompt_variant: str = "A",
) -> str:
    """
    Generate an administrator-facing explanation
    of deterministic enrolment analysis and
    forecasting results.

    Numerical values are calculated elsewhere by
    Python services. The LLM is used only to explain
    the supplied results.

    Parameters
    ----------
    trend_summary:
        Deterministic historical trend results.

    forecast_result:
        Deterministic forecasting and backtesting
        results.

    capacity:
        Optional institution capacity value.

    model_name:
        Optional Ollama model override.
        If not supplied, the model from .env is used.

    prompt_variant:
        Prompt variation to use:
        A = structured administrator explanation
        B = evidence-first explanation
        C = concise decision-support explanation

    Returns
    -------
    str
        The final explanation generated by Ollama.
    """

    # --------------------------------------------------
    # 1. CHOOSE OLLAMA MODEL
    # --------------------------------------------------

    selected_model_name = (
        model_name
        if model_name is not None
        else OLLAMA_MODEL
    )


    # --------------------------------------------------
    # 2. BUILD VERIFIED USER PROMPT
    # --------------------------------------------------

    user_prompt = build_forecast_prompt(
        trend_summary=trend_summary,
        forecast_result=forecast_result,
        capacity=capacity,
        variant=prompt_variant,
    )


    # --------------------------------------------------
    # 3. BUILD OLLAMA REQUEST
    # --------------------------------------------------

    payload = {
        "model": selected_model_name,

        "messages": [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": user_prompt,
            },
        ],

        # Prevent Qwen's reasoning process from
        # being displayed to the administrator.
        "think": False,

        # Return the complete response rather than
        # streaming token-by-token for now.
        "stream": False,

        # Low temperature makes administrative
        # explanations more consistent and less random.
        "options": {
            "temperature": 0.2,
        },
    }


    # --------------------------------------------------
    # 4. SEND REQUEST TO OLLAMA
    # --------------------------------------------------

    try:

        response = requests.post(
            f"{OLLAMA_BASE_URL}/api/chat",
            json=payload,
            timeout=120,
        )

        response.raise_for_status()


    except requests.RequestException as error:

        raise RuntimeError(
            "The AI explanation service is currently "
            f"unavailable: {error}"
        ) from error


    # --------------------------------------------------
    # 5. READ RESPONSE
    # --------------------------------------------------

    try:

        response_data = response.json()

        explanation = (
            response_data["message"]["content"]
        )

    except (
        ValueError,
        KeyError,
        TypeError,
    ) as error:

        raise RuntimeError(
            "Ollama returned an unexpected or "
            "malformed response."
        ) from error


    # --------------------------------------------------
    # 6. CHECK EMPTY RESPONSE
    # --------------------------------------------------

    if not explanation.strip():

        raise RuntimeError(
            "Ollama returned an empty explanation."
        )


    # --------------------------------------------------
    # 7. RETURN FINAL EXPLANATION
    # --------------------------------------------------

    return explanation.strip()